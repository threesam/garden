// The threesam wordmark as a dot grid.
//
// Michroma letterforms resolved onto a 171x24 grid, dilated so the
// stems land 3-4 dots thick, then hand-corrected dot by dot. This is the same
// geometry as static/assets/threesam-wordmark.svg — that file is this data
// flattened to circles for the OG card and any static use.
//
// Split per letter so the wordmark keeps one span per glyph: the snake easter
// egg collapses letters individually, which a single image could not do. `x0`
// is the letter's column in the full grid, so a field sampled in grid space
// stays continuous across the whole word instead of restarting per letter.

export interface WordmarkLetter {
  readonly ch: string;
  /** Column of this letter's left edge within the full `COLS`-wide grid. */
  readonly x0: number;
  /**
   * Empty grid columns between this letter's right edge and the next letter's
   * left edge. Cropping each glyph to its ink box discards the wordmark's own
   * letter-spacing, so it is carried here and re-applied as a trailing margin.
   */
  readonly gap: number;
  /** One string per row, '1' where a dot sits. */
  readonly rows: readonly string[];
}

export const COLS = 171;
export const ROWS = 24;
/** Dot diameter as a fraction of the grid pitch. */
export const FILL = 0.86;

